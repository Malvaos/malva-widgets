#!/usr/bin/env python3
"""Generate ui/pages/widgets_page.slint: every widget at every size and state, packed in rows."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
W = {"s": (160, 160), "m": (336, 160), "l": (336, 336), "xl": (688, 336)}
NAMES = {"cpu": "CpuWidget", "mem": "MemoryWidget", "disk": "DiskWidget", "net": "NetworkWidget", "gpu": "GpuWidget",
         "proc": "ProcessesWidget", "start": "StartupWidget", "act": "ActionsWidget", "sys": "SystemWidget"}
SIZES = {"cpu": "slm", "mem": "slm", "disk": "slm", "net": "slm", "gpu": "slm", "proc": "slm", "start": "sm", "act": "sm", "sys": "x"}

sections = []
sections.append(("Large", "336 x 336. Graph, facts and the busiest processes.",
                 [(k, "l", "", k) for k in ("cpu", "mem", "disk", "net", "gpu", "proc")]))
sections.append(("Medium", "336 x 160. One number and a small graph.",
                 [(k, "m", "", k) for k in ("cpu", "mem", "disk", "net", "gpu", "proc", "start", "act")]))
sections.append(("Small", "160 x 160. A ring or a single value.",
                 [(k, "s", "", k) for k in ("cpu", "mem", "disk", "net", "gpu", "proc", "start", "act")]))
sections.append(("System", "688 x 336. Everything at a glance.", [("sys", "xl", "", "system")]))
sections.append(("States", "Hover, warning, critical, paused, loading, error and edit mode (CPU, large).",
                 [("cpu", "l", "mode: WMode.hover;", "hover"), ("cpu", "l", "status: WStatus.warn;", "warning"),
                  ("cpu", "l", "status: WStatus.crit;", "critical"), ("cpu", "l", "status: WStatus.paused;", "paused"),
                  ("cpu", "l", "status: WStatus.loading;", "loading"), ("cpu", "l", "status: WStatus.error;", "error"),
                  ("cpu", "l", "mode: WMode.edit;", "edit mode")]))

PAGE_W = 1264
PAD = 28
GAP = 24
out = []
y = PAD
out.append('PageHead { x: %dpx; y: %dpx; width: %dpx; title: "Widgets"; note: "Nine widgets in four sizes. Hover one to see its menu button; every one has the same set of states."; }' % (PAD, y, PAGE_W - 2 * PAD))
y += 76 + 20
for title, note, items in sections:
    out.append('SectionHead { x: %dpx; y: %dpx; width: %dpx; title: "%s"; note: "%s"; }' % (PAD, y, PAGE_W - 2 * PAD, title, note))
    y += 52 + 20
    x = PAD
    row_h = 0
    for key, sz, extra, cap in items:
        w, h = W[sz]
        if x + w > PAGE_W - PAD and x > PAD:
            x = PAD
            y += row_h + GAP
            row_h = 0
        out.append('%s { x: %dpx; y: %dpx; size: WSize.%s; %s }' % (NAMES[key], x, y, sz if sz != "xl" else "xl", extra) if key != "sys"
                   else '%s { x: %dpx; y: %dpx; %s }' % (NAMES[key], x, y, extra))
        if title == "States":
            out.append('Caption { x: %dpx; y: %dpx; width: %dpx; height: 18px; text: "%s"; }' % (x, y + h + 6, w, cap))
        x += w + GAP
        row_h = max(row_h, h + (24 if title == "States" else 0))
    y += row_h + 40
height = y + PAD - 40
src = """// GENERATED by tools/gen_pages.py. Do not edit by hand.
// Every widget at every size, plus the states.

import { Theme } from "../theme.slint";
import { WSize, WStatus, WMode } from "../widgets/parts.slint";
import { CpuWidget, MemoryWidget, DiskWidget, NetworkWidget, GpuWidget } from "../widgets/resources.slint";
import { ProcessesWidget, StartupWidget, ActionsWidget, SystemWidget } from "../widgets/others.slint";
import { PageHead, SectionHead, Caption } from "common.slint";

export component WidgetsPage inherits Rectangle {
    width: %dpx;
    height: %dpx;
    background: transparent;
%s
}
""" % (PAGE_W, height, "\n".join("    " + l for l in out))
open(os.path.join(ROOT, "ui", "pages", "widgets_page.slint"), "w").write(src)
print("widgets_page.slint", PAGE_W, height)
