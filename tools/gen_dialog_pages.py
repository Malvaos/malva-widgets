def page(name, title, note, cols):
    """cols: [[(family title, family note, [(label, code), ...]), ...], ...]"""
    colx = [40, 652]
    out = []
    out.append("export component %s inherits Rectangle {\n    width: 1264px;\n    background: transparent;\n" % name)
    out.append("    Backdrop { x: 0px; y: 0px; width: parent.width; height: parent.height; }\n")
    out.append('    Title { x: 40px; y: 36px; width: 1184px; title: "%s"; note: "%s"; }\n' % (title, note))
    n = 0
    bottoms = []
    for ci, fams in enumerate(cols):
        prev = "128px"
        for ft, fn, items in fams:
            n += 1
            fid = "f%d" % n
            out.append('    %s := Fam { x: %dpx; y: %s; width: 580px; title: "%s"; note: "%s"; }\n' % (fid, colx[ci], prev, ft, fn))
            prev = "%s.y + %s.height + 22px" % (fid, fid)
            for label, code in items:
                n += 1
                lid, did = "l%d" % n, "d%d" % n
                out.append('    %s := Lab { x: %dpx; y: %s; width: 580px; text: "%s"; }\n' % (lid, colx[ci], prev, label))
                out.append('    %s := %s\n' % (did, code.replace("{", "{ x: %dpx; y: %s.y + 28px; " % (colx[ci], lid), 1)))
                prev = "%s.y + %s.height + 30px" % (did, did)
            prev = prev + " + 14px"
        bottoms.append(prev)
    out.append("    height: Math.max(%s) + 30px;\n" % ", ".join("(%s)" % b for b in bottoms))
    out.append("}\n\n")
    return "".join(out)

