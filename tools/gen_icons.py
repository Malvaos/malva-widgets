#!/usr/bin/env python3
"""Generate ui/icons.slint from a table of Font Awesome Free (solid) path data.

The table lives in tools/icons.json: {"name": [viewbox_width, "path d"]}.
Run:  python3 tools/gen_icons.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

icons = json.load(open(os.path.join(HERE, "icons.json")))

out = []
out.append("// GENERATED by tools/gen_icons.py. Do not edit by hand.")
out.append("// Icons: Font Awesome Free 6 (solid), CC BY 4.0, https://fontawesome.com/license/free")
out.append("// Every icon is drawn on a 512 unit tall grid; `w` is the grid width (some are wider).")
out.append("")
out.append("export struct IconDef { w: float, d: string }")
out.append("")
out.append("export global Icons {")
for name in sorted(icons):
    w, d = icons[name]
    out.append('    out property <IconDef> %s: { w: %d, d: "%s" };' % (name, w, d))
out.append("}")
out.append("")
open(os.path.join(ROOT, "ui", "icons.slint"), "w").write("\n".join(out))
print("wrote ui/icons.slint with %d icons" % len(icons))
